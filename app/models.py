class Appointment(Base):
    """A single booked slot.

    **Double-booking prevention lives here**, in ``uq_active_doctor_slot``: a
    *partial* unique index over ``(doctor_id, start_at)`` restricted to the
    blocking statuses. Two concurrent transactions inserting the same slot
    cannot both succeed — the loser gets an ``IntegrityError`` which the router
    translates into ``409 SLOT_TAKEN``. Cancelled/expired rows fall out of the
    index, so a released slot becomes bookable again with no cleanup.
    """

    __tablename__ = "appointments"
    __table_args__ = (
        Index(
            "uq_active_doctor_slot",
            "doctor_id",
            "start_at",
            unique=True,
            sqlite_where=text(_BLOCKING_SQL),
            postgresql_where=text(_BLOCKING_SQL),
        ),
        Index("ix_appointments_doctor_window", "doctor_id", "start_at"),
        Index("ix_appointments_patient_window", "patient_id", "start_at"),
        Index("ix_appointments_status_start", "status", "start_at"),
        CheckConstraint(
            "status IN ('held','confirmed','completed','cancelled','expired','no_show')",
            name="ck_appointment_status",
        ),
        CheckConstraint("end_at > start_at", name="ck_appointment_time_order"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    #: Human-friendly reference shown in emails/UI, e.g. ``APT-7K3QD2``.
    reference: Mapped[str] = mapped_column(String(16), unique=True, nullable=False, index=True)
    doctor_id: Mapped[int] = mapped_column(ForeignKey("doctor_profiles.id", ondelete="CASCADE"), nullable=False)
    patient_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), nullable=False)

    start_at: Mapped[datetime] = mapped_column(UTCDateTime(), nullable=False)
    end_at: Mapped[datetime] = mapped_column(UTCDateTime(), nullable=False)
    status: Mapped[str] = mapped_column(String(16), nullable=False, default=AppointmentStatus.HELD)

    #: While ``status == 'held'`` the slot is reserved until this instant.
    hold_expires_at: Mapped[datetime | None] = mapped_column(UTCDateTime(), index=True)
    confirmed_at: Mapped[datetime | None] = mapped_column(UTCDateTime())

    reason_for_visit: Mapped[str | None] = mapped_column(String(255))
    mode: Mapped[str] = mapped_column(String(16), default="in_person", nullable=False)

    cancelled_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    cancelled_by: Mapped[str | None] = mapped_column(String(24))
    cancellation_reason: Mapped[str | None] = mapped_column(String(255))

    #: Set when a booking is moved; points at the slot it came from (audit trail).
    rescheduled_from_at: Mapped[datetime | None] = mapped_column(UTCDateTime())
    reschedule_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    #: Google Calendar event ids, one per attendee calendar.
    patient_calendar_event_id: Mapped[str | None] = mapped_column(String(255))
    doctor_calendar_event_id: Mapped[str | None] = mapped_column(String(255))

    reminder_sent_at: Mapped[datetime | None] = mapped_column(UTCDateTime())

    created_at: Mapped[datetime] = mapped_column(UTCDateTime(), default=utcnow, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime(), default=utcnow, onupdate=utcnow, nullable=False)

    doctor: Mapped[DoctorProfile] = relationship()
    patient: Mapped[User] = relationship()
    symptom_report: Mapped["SymptomReport | None"] = relationship(
        back_populates="appointment", uselist=False, cascade="all, delete-orphan"
    )
    previsit_summary: Mapped["PreVisitSummary | None"] = relationship(
        back_populates="appointment", uselist=False, cascade="all, delete-orphan"
    )
    consultation: Mapped["Consultation | None"] = relationship(
        back_populates="appointment", uselist=False, cascade="all, delete-orphan"
    )

    @property
    def is_active(self) -> bool:
        return self.status in BLOCKING_STATUSES


