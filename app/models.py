class Role(enum.StrEnum):
    PATIENT = "patient"
    DOCTOR = "doctor"
    ADMIN = "admin"


class AppointmentStatus(enum.StrEnum):
    HELD = "held"              # slot reserved, symptom form pending
    CONFIRMED = "confirmed"    # booked
    COMPLETED = "completed"    # visit done, notes filed
    CANCELLED = "cancelled"    # cancelled by patient/doctor/admin
    EXPIRED = "expired"        # hold timed out without confirmation
    NO_SHOW = "no_show"


#: Statuses that occupy a slot. The partial unique index below is built on this
#: set — it is the single source of truth for "is this slot taken?".
BLOCKING_STATUSES: tuple[str, ...] = (AppointmentStatus.HELD, AppointmentStatus.CONFIRMED)
_BLOCKING_SQL = "status IN ('held','confirmed')"


