"""SQLAlchemy ORM models.

Schema conventions
------------------
* All timestamps are stored **timezone-aware in UTC**. The clinic's local
  timezone is a presentation concern handled in ``app.services.slots``.
* Enum-like columns are ``String`` + a Python ``StrEnum`` rather than a native
  database ENUM. Native enums require a migration to add a value; strings do
  not, and the constraint is expressed with ``CheckConstraint`` so the database
  still rejects garbage.
* Anything that talks to a third party (email, calendar) is persisted as an
  *outbox row* first and delivered by a background worker. The request path
  never depends on a third party being up.
"""

from __future__ import annotations

import enum
from datetime import datetime, timezone

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    Time,
    UniqueConstraint,
    text,
)
from sqlalchemy.types import TypeDecorator
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class UTCDateTime(TypeDecorator):
    """A timestamp column that is *always* timezone-aware UTC in Python.

    Postgres stores ``timestamptz`` and hands back aware datetimes; SQLite has
    no timezone type and hands back **naive** ones. Without this decorator every
    comparison against :func:`utcnow` would raise
    ``can't compare offset-naive and offset-aware datetimes`` on SQLite while
    working fine on Postgres — the worst kind of bug, one that only appears on
    the other environment.

    So normalisation happens once, at the type boundary: everything is
    converted to UTC on the way in, and re-attached to UTC on the way out.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect):
        if value is None:
            return None
        if value.tzinfo is None:
            value = value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)

    def process_result_value(self, value: datetime | None, dialect):
        if value is None:
            return None
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)


